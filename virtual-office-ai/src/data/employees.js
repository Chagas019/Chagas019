const BASE_TOOLS = ['consultar_tarefas', 'consultar_entregas', 'consultar_equipe', 'registrar_progresso', 'solicitar_informacao', 'reportar_bloqueio', 'entregar', 'arquivos_salvar', 'arquivos_listar'];
const ESFORCO = { executivo: 'high', diretor: 'high', gerente: 'medium', especialista: 'medium', assistente: 'low' };
const COR = { diretoria: '#1f2937', marketing: '#7c3aed', comercial: '#0369a1', atendimento: '#0f766e', tecnologia: '#b45309', financeiro: '#15803d', administrativo: '#be123c' };

// Completa os campos derivados: ferramentas básicas, criar_tarefa para quem delega, revisar_entrega para
// quem revisa, solicitar_aprovacao para quem pode pedir ações, e os tipos comuns a todos (conversa, tarefa geral).
function emp(e) {
  const tipos = [...new Set([...e.tipos, 'tarefa_geral', 'conversa'])];
  const delega = e.delega || [];
  const acoes = e.acoes || [];
  const ferramentas = [...new Set([
    ...BASE_TOOLS,
    ...(delega.length ? ['criar_tarefa'] : []),
    ...(tipos.includes('revisao_qualidade') ? ['revisar_entrega'] : []),
    ...(acoes.length ? ['solicitar_aprovacao'] : []),
    ...(e.ferramentas || []),
  ])];
  return { restricoes: [], esforco: ESFORCO[e.nivel], cor: COR[e.dep], ...e, tipos, delega, acoes, ferramentas };
}

