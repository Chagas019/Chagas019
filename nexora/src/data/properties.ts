const photo = (path: string, alt: string, roomId?: string, size: [number, number] = [1600, 1067], thumbW = 800): Media => ({
  src: `/media/${path}.webp`,
  thumb: `/media/${path}-${thumbW}.webp`,
  alt,
  width: size[0],
  height: size[1],
  roomId,
  caption: RENDER,
});

/** Panoramas renderizados dentro do modelo da Casa Horizonte; as setas apontam para o ambiente vizinho */
function panoramas(list: { roomId: string; name: string; file: string; position: [number, number, number] }[], links: Record<string, string[]>): Panorama[] {
  return list.map((p) => ({
    roomId: p.roomId,
    name: p.name,
    src: `/media/${p.file}.webp`,
    demonstrative: true,
    position: p.position,
    links: (links[p.roomId] ?? []).map((to) => {
      const q = list.find((x) => x.roomId === to)!;
      const dx = q.position[0] - p.position[0];
      const dz = q.position[2] - p.position[2];
      const dy = q.position[1] - p.position[1];
      return { to, yaw: Math.round((Math.atan2(dx, -dz) * 180) / Math.PI), pitch: Math.round((Math.atan2(dy, Math.hypot(dx, dz)) * 180) / Math.PI) };
    }),
  }));
}

