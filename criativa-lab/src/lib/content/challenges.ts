export const DAILY_CHALLENGES = CHALLENGES.filter((c) => c.kind === "diario");
export const challengeBySlug = (slug: string) => CHALLENGES.find((c) => c.slug === slug);

/** Desafio do dia: determinístico pela data (todos os usuários veem o mesmo no dia). */
export function challengeOfTheDay(date = new Date()): Challenge {
  const start = Date.UTC(2025, 0, 1);
  const today = Date.UTC(date.getFullYear(), date.getMonth(), date.getDate());
  const day = Math.floor((today - start) / 86_400_000);
  const list = DAILY_CHALLENGES;
  return list[((day % list.length) + list.length) % list.length];
}
